from checker import build_url, is_https, show_response, check_site, scan_sites, check_headers, retry_check, SITES

print("Partea 1:")
print("Partea 1, build_url fara slash:", build_url("example.com", "login"))
print("Partea 1, build_url cu slash:", build_url("example.com", "/login"))
print("Partea 1, build_url subcale:", build_url("example.com", "/a/b"))
print("Partea 1, is_https https:", is_https("https://example.com"))
print("Partea 1, is_https http:", is_https("http://example.com"))
print("Partea 1, is_https httpbin json:", is_https("https://httpbin.org/json"))
print("Partea 1, is_https invalid http:", is_https("http://this-site-does-not-exist.invalid"))

print("")
print("Partea 2:")
print("Partea 2, show_response example.com:")
show_response("https://example.com")
print("Partea 2, show_response httpbin html:")
show_response("https://httpbin.org/html")
print("Partea 2, show_response site inexistent:")
show_response("http://this-site-does-not-exist.invalid")

print("")
print("Partea 3:")
for url in SITES:
    print("Partea 3, check_site:", url, check_site(url))
print("Partea 3, check_site caz limita (404):", check_site("https://httpbin.org/status/404"))
print("Partea 3, check_site caz limita (inexistent):", check_site("http://this-site-does-not-exist.invalid"))

print("")
print("Partea 4:")
scan_sites()

print("")
print("Partea 5:")
print("Partea 5, check_headers example.com:", check_headers("https://example.com"))
print("Partea 5, check_headers toate prezente:", check_headers("https://httpbin.org/response-headers?X-Frame-Options=DENY&X-Content-Type-Options=nosniff"))
print("Partea 5, check_headers lowercase:", check_headers("https://httpbin.org/response-headers?x-frame-options=DENY"))
print("Partea 5, check_headers inexistent:", check_headers("http://this-site-does-not-exist.invalid"))

print("")
print("Partea 6:")
print("Partea 6, retry_check 200:", retry_check("https://httpbin.org/status/200"))
print("Partea 6, retry_check 404:", retry_check("https://httpbin.org/status/404"))
print("Partea 6, retry_check 500:", retry_check("https://httpbin.org/status/500"))
print("Partea 6, retry_check 500 attempts=2:", retry_check("https://httpbin.org/status/500", attempts=2))
print("Partea 6, retry_check inexistent:", retry_check("http://this-site-does-not-exist.invalid"))
